"""Synthetic logs for demo and tests. NOT real measurements.

The error model is simple but has the two properties that matter:
  * white noise (independent from fix to fix), and
  * a slowly wandering, time-correlated part (first-order Gauss-Markov),
    which is what real GNSS errors look like (multipath, atmosphere).
The urban session also has occasional multipath jumps.
"""
from __future__ import annotations

from pathlib import Path

import numpy as np

from .geo import enu_to_geodetic
from .kalman import K68

REF = (47.4979, 19.0402, 120.0)   # arbitrary origin (lat, lon, h)
T0 = 1_780_000_000.0              # arbitrary start time, unix seconds
HEADER = "# SYNTHETIC DATA generated by 'gnsslab simulate' - not a real recording"


def gauss_markov(n, sigma, tau, dt, rng):
    """Stationary first-order Gauss-Markov process with std sigma, correlation time tau."""
    phi = np.exp(-dt / tau)
    x = np.zeros(n)
    x[0] = rng.normal(0, sigma)
    w = rng.normal(0, sigma * np.sqrt(1 - phi ** 2), n)
    for k in range(1, n):
        x[k] = phi * x[k - 1] + w[k]
    return x


def _jumps(n, rng, prob=0.008, size=(10, 25), length=(5, 20)):
    """Multipath-like jumps: sudden offsets that last several seconds."""
    je, jn = np.zeros(n), np.zeros(n)
    k = 0
    while k < n:
        if rng.random() < prob:
            m = int(rng.integers(*length))
            a, r = rng.uniform(0, 2 * np.pi), rng.uniform(*size)
            je[k:k + m] += r * np.sin(a)
            jn[k:k + m] += r * np.cos(a)
            k += m
        k += 1
    return je, jn


def static_session(env: str, duration=900, dt=1.0, seed=0, offset=(0.0, 0.0)):
    rng = np.random.default_rng(seed)
    n = int(duration / dt)
    t = T0 + np.arange(n) * dt
    if env == "open":
        w, g, tau, rep = 0.6, 1.2, 90.0, 1.34
        je = jn = np.zeros(n)
    elif env == "urban":
        w, g, tau, rep = 2.0, 4.5, 45.0, 3.0   # phone under-reports its error here
        je, jn = _jumps(n, rng)
    else:
        raise ValueError(env)
    e = offset[0] + rng.normal(0, w, n) + gauss_markov(n, g, tau, dt, rng) + je
    no = offset[1] + rng.normal(0, w, n) + gauss_markov(n, g, tau, dt, rng) + jn
    u = rng.normal(0, 1.7 * w, n) + gauss_markov(n, 1.7 * g, tau, dt, rng)
    acc = K68 * rep * np.exp(rng.normal(0, 0.2, n))
    lat, lon, h = enu_to_geodetic(e, no, u, *REF)
    return t, lat, lon, h, acc


def drive_truth(duration=900, dt=0.1, seed=0):
    """Car-like path: straights, 45/90 degree turns, a few stops."""
    rng = np.random.default_rng(seed)
    segs, total = [], 0.0
    while total < duration:
        r = rng.random()
        if r < 0.55:
            seg = (rng.uniform(20, 60), rng.uniform(10, 20), 0.0)
        elif r < 0.92:
            ang = rng.choice([-90, 90, -45, 45])
            length = rng.uniform(5, 10)
            seg = (length, rng.uniform(5, 8), np.radians(ang) / length)
        else:
            seg = (rng.uniform(8, 20), 0.0, 0.0)
        segs.append(seg)
        total += seg[0]

    t, e, n, v, hdg = [], [], [], [], []
    te = x = y = speed = heading = 0.0
    for length, target, yaw in segs:
        for _ in range(int(length / dt)):
            speed += (target - speed) * dt / 3.0          # smooth speed changes
            if speed > 0.5:
                heading += yaw * dt
            x += speed * np.sin(heading) * dt
            y += speed * np.cos(heading) * dt
            te += dt
            t.append(te), e.append(x), n.append(y), v.append(speed), hdg.append(heading)
    t, e, n, v = map(np.array, (t, e, n, v))
    keep = t <= duration
    return t[keep], e[keep], n[keep], v[keep]


def drive_session(duration=900, seed=0):
    rng = np.random.default_rng(seed + 100)
    tt, te, tn, tv = drive_truth(duration, seed=seed)
    step = 10                                  # 0.1 s integration -> 1 Hz fixes
    t, e, n, v = tt[::step], te[::step], tn[::step], tv[::step]
    m = len(t)
    w, g, tau = 1.0, 1.5, 30.0
    em = e + rng.normal(0, w, m) + gauss_markov(m, g, tau, 1.0, rng)
    nm = n + rng.normal(0, w, m) + gauss_markov(m, g, tau, 1.0, rng)
    acc = K68 * np.hypot(w, g) * np.exp(rng.normal(0, 0.15, m))
    lat, lon, h = enu_to_geodetic(em, nm, np.zeros(m), *REF)
    spd = np.maximum(v + rng.normal(0, 0.3, m), 0)
    return T0 + t, lat, lon, h, acc, spd


def write_gnsslogger(path, t, lat, lon, h, acc, rng):
    cols = ("Fix,Provider,LatitudeDegrees,LongitudeDegrees,AltitudeMeters,SpeedMps,"
            "AccuracyMeters,BearingDegrees,UnixTimeMillis")
    lines = [HEADER, "# " + cols]
    for k in range(len(t)):
        lines.append(f"Fix,GPS,{lat[k]:.8f},{lon[k]:.8f},{h[k]:.2f},0.0,{acc[k]:.2f},,{int(t[k] * 1000)}")
        if k % 5 == 0:   # fused/network fixes appear in real logs too; the loader must skip them
            lines.append(f"Fix,FLP,{lat[k] + rng.normal(0, 2e-5):.8f},{lon[k]:.8f},"
                         f"{h[k]:.2f},0.0,15.0,,{int(t[k] * 1000) + 300}")
    Path(path).write_text("\n".join(lines) + "\n")


def write_csv(path, t, lat, lon, h, acc, spd):
    lines = [HEADER, "unix_time_ms,lat,lon,alt,accuracy,speed,provider"]
    lines += [f"{int(t[k] * 1000)},{lat[k]:.8f},{lon[k]:.8f},{h[k]:.2f},{acc[k]:.2f},{spd[k]:.2f},gps"
              for k in range(len(t))]
    Path(path).write_text("\n".join(lines) + "\n")


def write_samples(out_dir, seed=1) -> list[Path]:
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    rng = np.random.default_rng(seed)
    paths = []
    for i, env in enumerate(("open", "urban")):
        p = out / f"static_{env}_sky.txt" if env == "open" else out / "static_urban.txt"
        write_gnsslogger(p, *static_session(env, seed=seed + i, offset=(i * 40.0, 0.0)), rng)
        paths.append(p)
    p = out / "drive.csv"
    write_csv(p, *drive_session(seed=seed))
    paths.append(p)
    return paths
